export const positionIncumbentName = (position: Position) =>
  position.incumbentId ? employeeName(position.incumbentId) : null;

export const licenceAttention = (position: Position) =>
  Boolean(position.licence && position.licence.status !== "Valid");

const delay = (ms = 420) => new Promise((r) => setTimeout(r, ms));

export const structureApi = {
  positions: async () => {
    await delay();
    return positions;
  },
  position: async (id: string) => {
    await delay();
    return positions.find((p) => p.id === id) ?? null;
  },
  orgUnits: async () => {
    await delay();
    return orgUnits;
  },
};
