/**
 * Establishment and organisation-structure mock data.
 *
 * Self-contained: positions, grade bands and organisation units, plus a small
 * async reader that mimics the latency of the rest of the mock service. Kept
 * separate from `data.ts` so the establishment model can evolve on its own,
 * but every entity, branch and employee reference below points at the shared
 * records in `data.ts` so the whole app tells one consistent story.
 */
import { employees, entities } from "./data";
import type { TimelineEvent } from "./types";

export type PositionStatus = "Vacant" | "Filled" | "Frozen" | "Closed";

export interface SalaryBand {
  currency: string;
  min: number;
  mid: number;
  max: number;
  /** Where the band came from, so pay decisions are explainable. */
  source: string;
  reviewedOn: string;
}

/**
 * A licence or certification the position cannot legally be occupied without.
 * Expiry is the hinge between the establishment record and fitness to work:
 * when the incumbent's certificate lapses, the person stops being deployable
 * even though the position itself is unchanged.
 */
export interface PositionLicence {
  name: string;
  authority: string;
  mandatory: boolean;
  renewalMonths: number;
  /** Expiry of the current incumbent's certificate, if the position is filled. */
  holderExpiry?: string;
  status: "Valid" | "Expiring soon" | "Expired" | "No holder";
  fitnessImpact: string;
}

export interface Establishment {
  reference: string;
  costCentre: string;
  fundingSource: string;
  currency: string;
  budgetedFte: number;
  actualFte: number;
  budgetedAnnualCost: number;
  actualAnnualCost: number;
  approvedBy: string;
  approvedOn: string;
  note: string;
}

export interface Position {
  id: string;
  positionNo: string;
  jobTitle: string;
  jobFamily: string;
  grade: string;
  entityId: string;
  branch: string;
  department: string;
  team: string;
  orgUnitId: string;
  fte: number;
  status: PositionStatus;
  /** Employee id from data.ts when the position is filled. */
  incumbentId?: string;
  incumbentFrom?: string;
  incumbentNote?: string;
  reportsTo: string;
  critical: boolean;
  /** True when the position sits inside the approved establishment plan. */
  withinEstablishment: boolean;
  funded: boolean;
  effectiveFrom: string;
  vacancyReason?: string;
  salaryBand: SalaryBand;
  qualifications: string[];
  competencies: { name: string; level: string; note: string }[];
  licence?: PositionLicence;
  establishment: Establishment;
  incumbency: TimelineEvent[];
}

export type OrgUnitKind = "Entity" | "Branch" | "Department" | "Team";

export interface OrgUnitLead {
  name: string;
  title: string;
  employeeId?: string;
  interim?: boolean;
}

export interface OrgUnit {
  id: string;
  parentId?: string;
  kind: OrgUnitKind;
  name: string;
  code: string;
  entityId: string;
  location: string;
  lead: OrgUnitLead;
  /** Employees currently on the books for this unit and everything below it. */
  headcount: number;
  /** Accepted pre-hires not yet started. */
  incoming: number;
  /** Employees serving notice or with a known end date. */
  leavers: number;
  positions: number;
  vacancies: number;
  note?: string;
}

const employeeName = (id: string) =>
  employees.find((e) => e.id === id)?.fullName ?? "Unknown employee";

export const entityName = (entityId: string) =>
  entities.find((e) => e.id === entityId)?.name ?? "Unknown entity";

export const shortEntityName = (entityId: string) =>
  entityName(entityId).split(" ").slice(0, 2).join(" ");

export const formatMoney = (amount: number, currency: string) =>
  new Intl.NumberFormat("en-GB", { style: "currency", currency, maximumFractionDigits: 0 }).format(
    amount,
  );

